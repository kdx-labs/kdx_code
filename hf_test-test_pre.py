# Import the necessary libraries
from transformers import AutoModelForCausalLM, AutoTokenizer
import torch

# 1. Load the model and tokenizer once so we don't reload it every time the function runs
model_name = "distilgpt2"
print("Loading model and tokenizer...")
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForCausalLM.from_pretrained(model_name)
print("Model loaded successfully!\n")

# 2. Define the reusable generation function
def generate_text(prompt, max_tokens=30, temp=0.7):
    """
    Takes a text prompt and returns the generated completion using Hugging Face.
    """
    # Tokenize the input text and convert to PyTorch tensors
    inputs = tokenizer(prompt, return_tensors="pt")

    # Generate tokens using the model
    outputs = model.generate(
        input_ids=inputs["input_ids"],
        max_new_tokens=max_tokens,
        do_sample=True,
        temperature=temp,
        pad_token_id=tokenizer.eos_token_id # Prevents warnings by defining the padding token
    )

    # Decode the full output back into human-readable text
    result = tokenizer.decode(outputs[0], skip_special_tokens=True)
    return result

